// Generates src/ar/faceMeshData.ts from MediaPipe's canonical face model.
import { writeFileSync } from 'node:fs';

const URL = 'https://raw.githubusercontent.com/google-ai-edge/mediapipe/master/mediapipe/modules/face_geometry/data/canonical_face_model.obj';
const N = 468;
const RINGS = [
  [33,7,163,144,145,153,154,155,133,173,157,158,159,160,161,246],
  [263,249,390,373,374,380,381,382,362,398,384,385,386,387,388,466],
  [78,95,88,178,87,14,317,402,318,324,308,191,80,81,82,13,312,311,310,415],
].map((r) => new Set(r));
const OVAL = [10,338,297,332,284,251,389,356,454,323,361,288,397,365,379,378,400,377,152,148,176,149,150,136,172,58,132,93,234,127,162,21,54,103,67,109];

const obj = await (await fetch(URL)).text();
const uvs = [];
const tris = [];
for (const line of obj.split('\n')) {
  const t = line.trim().split(/\s+/);
  if (t[0] === 'vt') uvs.push([+t[1], 1 - +t[2]]);
  else if (t[0] === 'f') {
    const v = t.slice(1).map((s) => +s.split('/')[0] - 1);
    for (let i = 1; i + 1 < v.length; i++) tris.push([v[0], v[i], v[i + 1]]);
  }
}
const inRange = tris.filter((t) => t.every((i) => i < N));
const kept = inRange.filter((t) => !RINGS.some((r) => t.every((i) => r.has(i))));
console.log(`uvs ${uvs.length}, tris ${tris.length}, <468 ${inRange.length}, kept ${kept.length}`);
RINGS.forEach((r, k) => console.log(`ring ${k} dropped`, inRange.filter((t) => t.every((i) => r.has(i))).length));

const edge = Array.from({ length: N }, (_, i) => (OVAL.includes(i) ? 0 : 1));
const f = (n) => +n.toFixed(6);
writeFileSync('src/ar/faceMeshData.ts', `// GENERATED by scripts/gen-face-mesh.mjs - do not edit.
export const FACE_UVS = new Float32Array([${uvs.slice(0, N).flatMap(([u, v]) => [f(u), f(v)]).join(',')}]);
export const FACE_INDICES = new Uint16Array([${kept.flat().join(',')}]);
export const FACE_EDGE = new Float32Array([${edge.join(',')}]);
`);
